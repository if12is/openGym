#!/usr/bin/env node
// Regenerates the per-language exercise instruction packs in frontend/src/instr/
// from the upstream dataset (hasaneyldrm/exercises-dataset). English stays inline
// in exercises-data.js; every other language ships as its own lazy-loaded pack.
// Arabic steps come from AymaneZizi/exercises-dataset (upstream has no `ar` pack).
//
//   node scripts/build-instructions.mjs [path-to-exercises.json]
//   node scripts/build-instructions.mjs --ar
//
// Without an argument the dataset is downloaded from the upstream repo.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const UPSTREAM = 'https://raw.githubusercontent.com/hasaneyldrm/exercises-dataset/main/data/exercises.json'
const AR_UPSTREAM = 'https://raw.githubusercontent.com/AymaneZizi/exercises-dataset/main/data/exercises.json'
const LANGS = ['es', 'fr', 'it', 'tr', 'ru', 'zh', 'hi', 'pl', 'ko']

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'frontend', 'src', 'instr')
const arOnly = process.argv.includes('--ar')
const localPath = process.argv.slice(2).find(a => !a.startsWith('--'))

mkdirSync(outDir, { recursive: true })

function writePack(lang, pack, note) {
  const file = join(outDir, lang + '.js')
  writeFileSync(file, '// generated by scripts/build-instructions.mjs' + (note ? ' — ' + note : ' — do not edit') + '\nexport default ' + JSON.stringify(pack) + '\n')
  console.log(`${file}: ${Object.keys(pack).length} exercises`)
}

if (!arOnly) {
  let raw
  if (localPath) {
    raw = readFileSync(localPath, 'utf8')
  } else {
    console.log('Downloading upstream dataset…')
    const res = await fetch(UPSTREAM)
    if (!res.ok) throw new Error('Download failed: HTTP ' + res.status)
    raw = await res.text()
  }
  const data = JSON.parse(raw)
  for (const lang of LANGS) {
    const pack = {}
    for (const ex of data) {
      const steps = ex.instruction_steps && ex.instruction_steps[lang]
      if (steps && steps.length) pack[ex.id] = steps
    }
    writePack(lang, pack)
  }
}

console.log('Downloading Arabic instruction dataset…')
const arRes = await fetch(AR_UPSTREAM)
if (!arRes.ok) throw new Error('Arabic dataset download failed: HTTP ' + arRes.status)
const arData = JSON.parse(await arRes.text())
const arPack = {}
for (const ex of arData) {
  const steps = ex.instruction_steps && ex.instruction_steps.ar
  if (steps && steps.length) arPack[ex.id] = steps
}
writePack('ar', arPack, 'Arabic steps from AymaneZizi/exercises-dataset')
